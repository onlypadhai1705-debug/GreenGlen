/**
 * Generate blurData entries for Archive/ images referenced in the gallery
 * Appends to existing lib/blurData.ts
 */
import sharp from 'sharp';
import { readFile, writeFile } from 'fs/promises';
import { join } from 'path';
import { fileURLToPath } from 'url';
import { dirname } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Archive images referenced in content.ts gallery
const ARCHIVE_IMAGES = [
  'room2.JPG',
  'viewfromwindow.JPG',
  'sideview.JPG',
  'oldgates.JPG',
  'playingarea.JPG',
  'nightviewanotherside.JPG',
  'culturedinnignarea.JPG',
  'artisanarea.JPG',
  'artisanarea2.JPG',
];

const ARCHIVE_DIR = join(__dirname, '../public/Archive');
const BLUR_FILE = join(__dirname, '../lib/blurData.ts');

async function generateBlurDataUrl(filePath) {
  const buffer = await sharp(filePath).resize(10).jpeg({ quality: 20 }).toBuffer();
  return `data:image/jpeg;base64,${buffer.toString('base64')}`;
}

async function main() {
  // Read existing blurData
  const existing = await readFile(BLUR_FILE, 'utf-8');
  const match = existing.match(/= ({[\s\S]*});?\s*$/);
  const blurMap = match ? JSON.parse(match[1]) : {};

  console.log('\n🖼️  Generating blur placeholders for Archive/ gallery images\n');

  for (const file of ARCHIVE_IMAGES) {
    const key = '/Archive/' + file;
    if (blurMap[key]) {
      console.log(`⏭  ${file} — already exists, skipping`);
      continue;
    }
    const filePath = join(ARCHIVE_DIR, file);
    process.stdout.write(`⏳ ${file}...`);
    try {
      blurMap[key] = await generateBlurDataUrl(filePath);
      console.log(' ✓');
    } catch (e) {
      console.log(` ❌ ${e.message}`);
    }
  }

  const tsContent = `// Auto-generated by scripts/ — DO NOT EDIT MANUALLY\nexport const blurData: Record<string, string> = ${JSON.stringify(blurMap, null, 2)};\n`;
  await writeFile(BLUR_FILE, tsContent, 'utf-8');
  console.log('\n✅  lib/blurData.ts updated\n');
}

main().catch(err => { console.error(err); process.exit(1); });
