/**
 * Image Optimization Script for Green Glen
 * Maps Archive/ photos → public/images/, compresses, generates blurDataURLs
 */
import sharp from 'sharp';
import { mkdir, writeFile, stat, copyFile } from 'fs/promises';
import { join } from 'path';
import { fileURLToPath } from 'url';
import { dirname } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const ARCHIVE_DIR = join(__dirname, '../public/Archive');
const OUTPUT_DIR = join(__dirname, '../public/images');

// Mapping: target image name → best matching Archive file
const IMAGE_MAP = {
  'hero-green-glen.jpg':     'dayfullview.JPG',
  'mudhouse-exterior.jpg':   'outerarea.JPG',
  'mudhouse-interior.jpg':   'room1.JPG',
  'open-space.jpg':          'chairsinnature.JPG',
  'home-food.jpg':           'artisandinningarea.JPG',
  'group-experience.jpg':    'daydinningview.JPG',
  'gallery-corporate.jpg':   'culturedinnignarea.JPG',
  'gallery-yoga.jpg':        'swingnightview.JPG',
  'sattal-location.jpg':     'dayviewanotherside.JPG',
  'cta-background.jpg':      'nightwholeview.JPG',
  'kainchi-dham.jpg':        'oldgates.JPG',
};

const JPEG_QUALITY = 72;
const BLUR_WIDTH = 10;

async function generateBlurDataUrl(buffer) {
  const blurBuf = await sharp(buffer)
    .resize(BLUR_WIDTH)
    .jpeg({ quality: 20 })
    .toBuffer();
  return `data:image/jpeg;base64,${blurBuf.toString('base64')}`;
}

async function main() {
  await mkdir(OUTPUT_DIR, { recursive: true });

  console.log('\n🖼️  Green Glen Image Optimization\n');

  const blurMap = {};
  let totalSaved = 0;

  for (const [target, source] of Object.entries(IMAGE_MAP)) {
    const srcPath = join(ARCHIVE_DIR, source);
    const dstPath = join(OUTPUT_DIR, target);
    const key = '/images/' + target;

    let srcBuffer;
    try {
      const { readFile } = await import('fs/promises');
      srcBuffer = await readFile(srcPath);
    } catch {
      console.log(`⚠️  SKIP ${target} — source not found: ${source}`);
      continue;
    }

    const beforeSize = srcBuffer.length;
    process.stdout.write(`⏳ ${target} (${(beforeSize/1024/1024).toFixed(1)} MB)...`);

    // Generate blur placeholder from original
    blurMap[key] = await generateBlurDataUrl(srcBuffer);

    // Compress → output
    await sharp(srcBuffer)
      .jpeg({ quality: JPEG_QUALITY, progressive: true, mozjpeg: true })
      .toFile(dstPath);

    const afterStat = await stat(dstPath);
    const afterSize = afterStat.size;
    const saved = beforeSize - afterSize;
    totalSaved += saved;

    console.log(` ✓ → ${(afterSize/1024/1024).toFixed(1)} MB  (-${(saved/1024/1024).toFixed(1)} MB, ${((saved/beforeSize)*100).toFixed(0)}%)`);
  }

  // Write blur map TypeScript file
  const outPath = join(__dirname, '../lib/blurData.ts');
  const tsContent = `// Auto-generated by scripts/optimize-images.mjs — DO NOT EDIT MANUALLY\nexport const blurData: Record<string, string> = ${JSON.stringify(blurMap, null, 2)};\n`;
  await writeFile(outPath, tsContent, 'utf-8');

  console.log(`\n✅  Total saved: ${(totalSaved/1024/1024).toFixed(1)} MB`);
  console.log(`📄  Blur placeholders → lib/blurData.ts`);
  console.log(`📁  Images → public/images/\n`);
}

main().catch(err => { console.error(err); process.exit(1); });
